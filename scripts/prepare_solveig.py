"""Build the Solveig (North Sea) field case from Sodir open data.

Inputs (downloaded from factpages.sodir.no, table view -> CSV, see data/raw/sodir/README.md):
    data/raw/sodir/facility_fixed.csv            template, manifold and host positions (ED50 lat/lon)
    data/raw/sodir/wellbore_development_all.csv  which production wells sit on which template
    data/raw/sodir/field_production_monthly.csv  monthly oil production (for the well rate)

Outputs:
    config/field_solveig.yaml                    wells, candidate manifold sites, host (local x/y in m)
    data/processed/solveig_production.csv        monthly oil rate per producing well (phase 1)

Coordinates: local east/north metres from an equirectangular projection about the real
manifold (error well below 0.1 % over 20 km), datum ED50 as given by Sodir.
"""
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from layout_rel.config import REPO_ROOT
from layout_rel.units import BBL, DAY

RAW = REPO_ROOT / "data" / "raw" / "sodir"
R_EARTH = 6371008.8          # m, mean Earth radius
FIELD, HOST = "SOLVEIG", "EDVARD GRIEG"
# phase-1 plateau used for the well rate (3 producers BA-1, BB-1, BC-1 on stream)
PLATEAU = ("2023-04", "2025-08")
PHASE1_PRODUCERS = 3


def latlon(f: pd.DataFrame) -> pd.DataFrame:
    deg = lambda r, p: r[p + "Deg"] + r[p + "Min"] / 60 + r[p + "Sec"] / 3600
    f = f.copy()
    f["lat"] = f.apply(lambda r: deg(r, "fclNs") * (1 if r.fclNsCode == "N" else -1), axis=1)
    f["lon"] = f.apply(lambda r: deg(r, "fclEw") * (1 if r.fclEwCode == "E" else -1), axis=1)
    return f


def main():
    fac = latlon(pd.read_csv(RAW / "facility_fixed.csv", encoding="utf-8-sig", low_memory=False))
    wells = pd.read_csv(RAW / "wellbore_development_all.csv", encoding="utf-8-sig", low_memory=False)
    prod = pd.read_csv(RAW / "field_production_monthly.csv", encoding="utf-8-sig", low_memory=False)

    f = fac[(fac.fclBelongsToName.astype(str).str.upper() == FIELD) | (fac.fclName.str.upper() == HOST)]
    ref = f[f.fclName.str.upper().str.contains("MANIFOLD")].iloc[0]
    lat0, lon0 = ref.lat, ref.lon
    f = f.assign(x=np.radians(f.lon - lon0) * R_EARTH * np.cos(np.radians(lat0)),
                 y=np.radians(f.lat - lat0) * R_EARTH)
    pos = {r.fclName: (round(float(r.x), 1), round(float(r.y), 1)) for r in f.itertuples()}

    # production wells (main bores, not observation pilots), one entry per well
    w = wells[(wells.wlbField == FIELD) & (wells.wlbPurpose == "PRODUCTION")]
    w = w.groupby("wlbWell").first().reset_index()
    well_list = []
    for r in w.sort_values("wlbWell").itertuples():
        x, y = pos[r.wlbProductionFacility]
        name = "W_" + r.wlbWell.split("-", 1)[1].replace("-", "")
        well_list.append({"name": name, "x": x, "y": y,
                          "template": r.wlbProductionFacility, "sodir_well": r.wlbWell})

    # candidate manifold sites: the real manifold, the two phase-2 templates, and the well centroid
    xs, ys = np.array([w_["x"] for w_ in well_list]), np.array([w_["y"] for w_ in well_list])
    man = [n for n in pos if "MANIFOLD" in n.upper()][0]
    sites = [
        {"name": "M_ACT", "x": pos[man][0], "y": pos[man][1], "note": f"real manifold ({man})"},
        {"name": "M_BF", "x": pos["16/4 SOLVEIG BF"][0], "y": pos["16/4 SOLVEIG BF"][1],
         "note": "at template BF (2 wells)"},
        {"name": "M_BG", "x": pos["16/4 SOLVEIG BG"][0], "y": pos["16/4 SOLVEIG BG"][1],
         "note": "at template BG (north, closest to host)"},
        {"name": "M_CEN", "x": round(float(xs.mean()), 1), "y": round(float(ys.mean()), 1),
         "note": "centroid of the 6 producing wells (cf. Silva & Guedes Soares 2025 Eqs. 44-45)"},
    ]
    host = f[f.fclName.str.upper() == HOST].iloc[0]
    data = {
        "name": "Solveig (North Sea, PL359) - 6 producing wells, host Edvard Grieg",
        "source": ("Sodir fact pages (factpages.sodir.no), tables facility_fixed and wellbore_development_all, "
                   "downloaded 2026-11-07; NLOD licence. Built by scripts/prepare_solveig.py."),
        "coordinates": f"local x = east, y = north [m] about {man}, ED50 lat/lon {lat0:.5f}, {lon0:.5f}",
        "water_depth_m": float(ref.fclWaterDepth),
        "host": {"name": "EDVARD_GRIEG", "type": "fixed jacket platform", "x": pos[host.fclName][0],
                 "y": pos[host.fclName][1]},
        "wells": [{k: v for k, v in w_.items()} for w_ in well_list],
        "manifold_sites": sites,
    }
    out = REPO_ROOT / "config" / "field_solveig.yaml"
    with out.open("w") as fh:
        fh.write("# GENERATED by scripts/prepare_solveig.py - do not edit by hand.\n")
        yaml.safe_dump(data, fh, sort_keys=False, allow_unicode=True)
    print(f"wrote {out}")

    # well rate from the phase-1 plateau
    p = prod[prod.prfInformationCarrier.astype(str).str.upper() == FIELD].copy()
    p["month"] = pd.to_datetime(dict(year=p.prfYear, month=p.prfMonth, day=1))
    p["days"] = p.month.dt.days_in_month
    p["oil_Sm3_per_day"] = p.prfPrdOilNetMillSm3 * 1e6 / p.days
    p["oil_bbl_per_day_per_well"] = p.oil_Sm3_per_day / PHASE1_PRODUCERS / BBL
    plateau = p[(p.month >= PLATEAU[0]) & (p.month <= PLATEAU[1])]
    p.to_csv(REPO_ROOT / "data" / "processed" / "solveig_production.csv", index=False)
    print(f"phase-1 plateau {PLATEAU[0]}..{PLATEAU[1]}: median oil "
          f"{plateau.oil_Sm3_per_day.median():.0f} Sm3/d field = "
          f"{plateau.oil_bbl_per_day_per_well.median():.0f} bbl/d per well "
          f"(mean {plateau.oil_bbl_per_day_per_well.mean():.0f})")


if __name__ == "__main__":
    main()
