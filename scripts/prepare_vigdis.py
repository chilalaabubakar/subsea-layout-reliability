"""Build the Vigdis field case (northern North Sea, tied back to Snorre A) from Sodir open data.

Second real field of the study: a short tie-back (about 8 km) and 13 producing wells on five
well templates spread over 8 km. Same inputs and coordinate method as scripts/prepare_solveig.py.

Outputs:
    config/field_vigdis.yaml                 wells, candidate manifold sites, host (local x/y in m)
    data/processed/vigdis_production.csv     yearly oil rate of the field

Wells: every wellbore with purpose PRODUCTION and status PRODUCING, one per well slot, placed
at its template (Sodir gives the template position, not the wellhead). Candidate manifold
sites: the five producing templates and the centroid of the wells.
"""
import importlib.util
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from layout_rel.config import REPO_ROOT
from layout_rel.units import BBL

_spec = importlib.util.spec_from_file_location("prepare_solveig", Path(__file__).with_name("prepare_solveig.py"))
ps = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ps)

RAW = REPO_ROOT / "data" / "raw" / "sodir"
FIELD, HOST = "VIGDIS", "SNORRE A"
PLATEAU_YEARS = (1998, 2006)        # years of the field plateau used for the well rate


def main():
    fac = ps.latlon(pd.read_csv(RAW / "facility_fixed.csv", encoding="utf-8-sig", low_memory=False))
    wells = pd.read_csv(RAW / "wellbore_development_all.csv", encoding="utf-8-sig", low_memory=False)
    prod = pd.read_csv(RAW / "field_production_monthly.csv", encoding="utf-8-sig", low_memory=False)

    w = wells[(wells.wlbField == FIELD) & (wells.wlbPurpose == "PRODUCTION") & (wells.wlbStatus == "PRODUCING")]
    w = w.groupby("wlbWell").first().reset_index().sort_values("wlbWell")
    templates = sorted(w.wlbProductionFacility.unique())
    f = fac[fac.fclName.isin(templates + [HOST])]
    ref = f[f.fclName == templates[0]].iloc[0]
    rx, ry = ps.local_scale(ref.lat)
    f = f.assign(x=np.radians(f.lon - ref.lon) * rx, y=np.radians(f.lat - ref.lat) * ry)
    pos = {r.fclName: (round(float(r.x), 1), round(float(r.y), 1)) for r in f.itertuples()}

    well_list = [{"name": "W_" + r.wlbWell.split("-", 1)[1].replace("-", ""), "label": r.wlbWell.split("-", 1)[1],
                  "x": pos[r.wlbProductionFacility][0], "y": pos[r.wlbProductionFacility][1],
                  "template": r.wlbProductionFacility, "sodir_well": r.wlbWell} for r in w.itertuples()]
    xs, ys = np.array([v["x"] for v in well_list]), np.array([v["y"] for v in well_list])
    sites = [{"name": "M_" + t.split()[-1], "label": f"$M_{{{t.split()[-1]}}}$", "x": pos[t][0], "y": pos[t][1],
              "note": f"at template {t} ({int((w.wlbProductionFacility == t).sum())} producing wells)"} for t in templates]
    sites.append({"name": "M_CEN", "label": "$M_{cen}$", "x": round(float(xs.mean()), 1), "y": round(float(ys.mean()), 1),
                  "note": f"centroid of the {len(well_list)} producing wells"})
    data = {"name": f"Vigdis (northern North Sea) - {len(well_list)} producing wells, host Snorre A",
            "source": ("Sodir fact pages (factpages.sodir.no), tables facility_fixed and wellbore_development_all, "
                       "downloaded 2026-11-07; NLOD licence. Built by scripts/prepare_vigdis.py."),
            "coordinates": f"local x = east, y = north [m] about {templates[0]}, ED50 lat/lon {ref.lat:.5f}, {ref.lon:.5f}",
            "water_depth_m": float(f[f.fclName.isin(templates)].fclWaterDepth.mean()),
            "host": {"name": "SNORRE_A", "label": "Snorre A", "type": "tension-leg platform", "x": pos[HOST][0], "y": pos[HOST][1]},
            "wells": well_list, "manifold_sites": sites}
    out = REPO_ROOT / "config" / "field_vigdis.yaml"
    with out.open("w") as fh:
        fh.write("# GENERATED by scripts/prepare_vigdis.py - do not edit by hand.\n")
        yaml.safe_dump(data, fh, sort_keys=False, allow_unicode=True)
    print(f"wrote {out}: {len(well_list)} wells on {len(templates)} templates")
    for s in sites:
        print(f"  {s['name']:6s} tie-back {np.hypot(s['x'] - pos[HOST][0], s['y'] - pos[HOST][1]) / 1000:5.2f} km  ({s['note']})")

    p = prod[prod.prfInformationCarrier.astype(str).str.upper() == FIELD]
    yr = p.groupby("prfYear").agg(oil_Sm3=("prfPrdOilNetMillSm3", lambda v: v.sum() * 1e6), months=("prfMonth", "count"))
    yr["oil_bbl_per_day"] = yr.oil_Sm3 / BBL / (yr.months * 365.25 / 12)
    yr.to_csv(REPO_ROOT / "data" / "processed" / "vigdis_production.csv")
    plat = yr.loc[PLATEAU_YEARS[0]:PLATEAU_YEARS[1], "oil_bbl_per_day"]
    print(f"field plateau {PLATEAU_YEARS[0]}-{PLATEAU_YEARS[1]}: mean {plat.mean():,.0f} bbl/d "
          f"= {plat.mean() / len(well_list):,.0f} bbl/d per well over {len(well_list)} wells")


if __name__ == "__main__":
    main()
